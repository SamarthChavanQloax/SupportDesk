import { PrismaClient, Role, TicketStatus, TicketPriority } from '@prisma/client';
import * as fs from 'fs';
import * as path from 'path';

const prisma = new PrismaClient();

interface TicketJsonItem {
  reference: string;
  title: string;
  description: string;
  status: TicketStatus;
  priority: TicketPriority;
  category?: string;
  slaDueTimeHours: string;
  customerEmail: string;
  assigneeEmail?: string;
}

async function main() {
  console.log('--- Starting SupportDesk Database Seed ---');

  // 1. Seed Foundational Users
  const usersData = [
    { email: 'alice.customer@example.com', name: 'Alice Johnson', role: Role.customer },
    { email: 'bob.customer@example.com', name: 'Bob Smith', role: Role.customer },
    { email: 'carol.customer@example.com', name: 'Carol Davis', role: Role.customer },
    { email: 'dave.agent@example.com', name: 'Dave Wilson', role: Role.agent },
    { email: 'emma.agent@example.com', name: 'Emma Taylor', role: Role.agent },
    { email: 'admin@supportdesk.internal', name: 'System Administrator', role: Role.admin }
  ];

  const userMap = new Map<string, number>();

  for (const u of usersData) {
    const user = await prisma.user.upsert({
      where: { email: u.email },
      update: { name: u.name, role: u.role, isActive: true },
      create: {
        email: u.email,
        name: u.name,
        role: u.role,
        isActive: true,
        passwordHash: '$2b$10$EpRnTzVlqHNP0.fUbXUwSOyUIXe/QLu7mOV1lE9m6wZ5Xz9uTzNKi' // Fictional test hash
      }
    });
    userMap.set(u.email, user.id);
  }
  console.log(`[SEED] Ensured ${userMap.size} foundational users.`);

  // 2. Seed Foundational Tags
  const tagsData = [
    { name: 'bug', color: '#E53E3E' },
    { name: 'billing', color: '#3182CE' },
    { name: 'security', color: '#DD6B20' },
    { name: 'ui', color: '#805AD5' },
    { name: 'performance', color: '#D69E2E' },
    { name: 'infrastructure', color: '#319795' }
  ];

  const tagMap = new Map<string, number>();
  for (const t of tagsData) {
    const tag = await prisma.tag.upsert({
      where: { name: t.name },
      update: { color: t.color },
      create: { name: t.name, color: t.color }
    });
    tagMap.set(t.name, tag.id);
  }
  console.log(`[SEED] Ensured ${tagMap.size} foundational tags.`);

  // 3. Load Sample Tickets from JSON generated by Day 5 tool
  const jsonPath = path.join(__dirname, '../data/sample-tickets.json');
  if (!fs.existsSync(jsonPath)) {
    throw new Error(`Seed JSON file not found at ${jsonPath}`);
  }

  const rawJson = fs.readFileSync(jsonPath, 'utf-8');
  const ticketsList: TicketJsonItem[] = JSON.parse(rawJson);

  console.log(`[SEED] Read ${ticketsList.length} tickets from JSON. Inserting into database...`);

  const now = new Date();

  for (const item of ticketsList) {
    const customerId = userMap.get(item.customerEmail);
    if (!customerId) {
      throw new Error(`Referenced customer email ${item.customerEmail} does not exist.`);
    }

    const assigneeId = item.assigneeEmail && item.assigneeEmail.length > 0
      ? userMap.get(item.assigneeEmail) || null
      : null;

    const hours = parseInt(item.slaDueTimeHours, 10) || 24;
    const slaDueTime = new Date(now.getTime() + hours * 3600 * 1000);

    const isResolved = item.status === TicketStatus.resolved;
    const isClosed = item.status === TicketStatus.closed;

    const resolvedAt = isResolved || isClosed ? new Date(now.getTime() - 2 * 3600 * 1000) : null;
    const closedAt = isClosed ? new Date(now.getTime() - 1 * 3600 * 1000) : null;

    const ticket = await prisma.ticket.upsert({
      where: { reference: item.reference },
      update: {
        title: item.title,
        description: item.description,
        status: item.status,
        priority: item.priority,
        category: item.category,
        slaDueTime,
        customerId,
        assigneeId,
        resolvedAt,
        closedAt
      },
      create: {
        reference: item.reference,
        title: item.title,
        description: item.description,
        status: item.status,
        priority: item.priority,
        category: item.category,
        slaDueTime,
        customerId,
        assigneeId,
        resolvedAt,
        closedAt
      }
    });

    // Attach a tag based on category if matched
    const categoryLower = (item.category || '').toLowerCase();
    let matchedTagId: number | undefined;
    if (categoryLower.includes('bill')) matchedTagId = tagMap.get('billing');
    else if (categoryLower.includes('sec')) matchedTagId = tagMap.get('security');
    else if (categoryLower.includes('ui') || categoryLower.includes('ux')) matchedTagId = tagMap.get('ui');
    else if (categoryLower.includes('perf')) matchedTagId = tagMap.get('performance');
    else if (categoryLower.includes('infra')) matchedTagId = tagMap.get('infrastructure');
    else matchedTagId = tagMap.get('bug');

    if (matchedTagId) {
      await prisma.ticketTag.upsert({
        where: {
          ticketId_tagId: {
            ticketId: ticket.id,
            tagId: matchedTagId
          }
        },
        update: {},
        create: {
          ticketId: ticket.id,
          tagId: matchedTagId
        }
      });
    }
  }

  // 4. Seed sample comments and audit log on the first two tickets
  const firstTicket = await prisma.ticket.findUnique({ where: { reference: 'TCK-2026-0001' } });
  if (firstTicket) {
    const daveId = userMap.get('dave.agent@example.com')!;
    const aliceId = userMap.get('alice.customer@example.com')!;

    // Initial customer comment
    await prisma.comment.create({
      data: {
        ticketId: firstTicket.id,
        authorId: aliceId,
        body: 'I have attached a screenshot of the login failure.',
        isInternal: false
      }
    });

    // Agent internal investigation note
    await prisma.comment.create({
      data: {
        ticketId: firstTicket.id,
        authorId: daveId,
        body: 'Checked OAuth logs: client clock skew caused token validation failure.',
        isInternal: true
      }
    });

    // Audit log
    await prisma.auditLog.create({
      data: {
        ticketId: firstTicket.id,
        actorId: daveId,
        action: 'TICKET_ASSIGNED',
        fieldChanged: 'assignee_id',
        oldValue: 'null',
        newValue: String(daveId)
      }
    });
  }

  // 5. Verification Count
  const totalTickets = await prisma.ticket.count();
  const openCount = await prisma.ticket.count({ where: { status: TicketStatus.open } });
  const inProgressCount = await prisma.ticket.count({ where: { status: TicketStatus.in_progress } });
  const waitingCount = await prisma.ticket.count({ where: { status: TicketStatus.waiting_on_customer } });
  const resolvedCount = await prisma.ticket.count({ where: { status: TicketStatus.resolved } });
  const closedCount = await prisma.ticket.count({ where: { status: TicketStatus.closed } });

  console.log('\n--- Seed Verification Results ---');
  console.log(`Total Tickets in Database: ${totalTickets}`);
  console.log(`Status breakdown: Open=${openCount}, InProgress=${inProgressCount}, Waiting=${waitingCount}, Resolved=${resolvedCount}, Closed=${closedCount}`);
}

main()
  .catch((e) => {
    console.error('Seed execution failed:', e);
    process.exit(1);
  })
  .finally(async () => {
    await prisma.$disconnect();
  });
