import { describe, it, expect, vi, beforeEach } from 'vitest';
import { render, screen, fireEvent, waitFor } from '@testing-library/react';
import { MemoryRouter, Routes, Route } from 'react-router-dom';
import { QueryClient, QueryClientProvider } from '@tanstack/react-query';
import { TicketDetailPage } from '../../../pages/TicketDetailPage';
import { CreateTicketPage } from '../../../pages/CreateTicketPage';
import * as ticketsApi from '../api/tickets.api';
import * as authModule from '../../../lib/auth';

vi.mock('../api/tickets.api', async (importOriginal) => {
  const actual = await importOriginal<typeof ticketsApi>();
  return {
    ...actual,
    fetchTicketById: vi.fn(),
    fetchComments: vi.fn(),
    createComment: vi.fn(),
    updateTicket: vi.fn(),
    streamSuggestReply: vi.fn(),
    categorizeTicket: vi.fn(),
  };
});

describe('AI Features Frontend UI', () => {
  let queryClient: QueryClient;

  const mockAgentUser = {
    id: 8,
    name: 'Dave Agent',
    email: 'dave@supportdesk.io',
    role: 'agent' as const,
  };

  const mockTicket = {
    id: 101,
    reference: 'TCK-2026-0101',
    title: 'Payment Gateway Timeout on Checkout',
    description: 'Customers on Stripe are experiencing intermittent 504 timeouts.',
    status: 'in_progress' as const,
    priority: 'P1' as const,
    category: 'Billing',
    customerId: 5,
    customer: { id: 5, name: 'Alice Smith', email: 'alice@example.com' },
    assigneeId: 8,
    assignee: { id: 8, name: 'Dave Agent', email: 'dave@supportdesk.io' },
    createdAt: new Date().toISOString(),
    updatedAt: new Date().toISOString(),
    comments: [
      {
        id: 1,
        ticketId: 101,
        authorId: 5,
        body: 'Getting a 504 error when submitting payment.',
        isInternal: false,
        createdAt: new Date().toISOString(),
        author: { id: 5, name: 'Alice Smith', role: 'customer' },
      },
    ],
  };

  beforeEach(() => {
    vi.clearAllMocks();
    queryClient = new QueryClient({
      defaultOptions: {
        queries: { retry: false, gcTime: 0 },
      },
    });

    vi.spyOn(authModule, 'useAuth').mockReturnValue({
      user: mockAgentUser,
      accessToken: 'mock-jwt-token',
      isAuthenticated: true,
      login: vi.fn(),
      logout: vi.fn(),
    });

    vi.mocked(ticketsApi.fetchTicketById).mockResolvedValue(mockTicket as any);
    vi.mocked(ticketsApi.fetchComments).mockResolvedValue(mockTicket.comments as any);
  });

  describe('Feature 1: Suggest Reply (Streaming Draft)', () => {
    it('streams suggested reply into draft box and allows agent to copy it to response box', async () => {
      vi.mocked(ticketsApi.streamSuggestReply).mockImplementation(async (_id, callbacks) => {
        callbacks.onChunk('Hi Alice, ');
        callbacks.onChunk('we are investigating the Stripe timeout.');
        callbacks.onDone?.({ model: 'gpt-4o-mini', totalTokens: 120 });
      });

      render(
        <QueryClientProvider client={queryClient}>
          <MemoryRouter initialEntries={['/tickets/101']}>
            <Routes>
              <Route path="/tickets/:id" element={<TicketDetailPage />} />
            </Routes>
          </MemoryRouter>
        </QueryClientProvider>
      );

      // Wait for ticket to load
      await screen.findByText('Payment Gateway Timeout on Checkout');

      // Find and click "✨ Suggest Reply with AI" button
      const suggestButton = screen.getByRole('button', { name: /suggest reply with ai/i });
      expect(suggestButton).toBeInTheDocument();

      fireEvent.click(suggestButton);

      // Verify draft appears streamed
      await waitFor(() => {
        expect(
          screen.getByText(/we are investigating the stripe timeout/i)
        ).toBeInTheDocument();
      });

      // Verify safety warning is displayed
      expect(
        screen.getByText(/this draft is generated by ai for agent review/i)
      ).toBeInTheDocument();

      // Click "Use Draft" to populate comment box
      const useDraftButton = screen.getByRole('button', { name: /use draft/i });
      fireEvent.click(useDraftButton);

      // Verify textarea contains the draft
      const textarea = screen.getByLabelText(/comment response text/i);
      expect(textarea).toHaveValue('Hi Alice, we are investigating the Stripe timeout.');

      // Draft box is dismissed after application
      expect(screen.queryByRole('region', { name: /ai generated reply draft/i })).toBeNull();
    });

    it('displays error banner when AI stream fails without sending any reply', async () => {
      vi.mocked(ticketsApi.streamSuggestReply).mockImplementation(async (_id, callbacks) => {
        callbacks.onError?.(new Error('OpenAI service unavailable (503)'));
      });

      render(
        <QueryClientProvider client={queryClient}>
          <MemoryRouter initialEntries={['/tickets/101']}>
            <Routes>
              <Route path="/tickets/:id" element={<TicketDetailPage />} />
            </Routes>
          </MemoryRouter>
        </QueryClientProvider>
      );

      await screen.findByText('Payment Gateway Timeout on Checkout');

      const suggestButton = screen.getByRole('button', { name: /suggest reply with ai/i });
      fireEvent.click(suggestButton);

      await waitFor(() => {
        expect(
          screen.getByText(/ai suggestion error: openai service unavailable \(503\)/i)
        ).toBeInTheDocument();
      });

      // Comment textarea remains untouched
      const textarea = screen.getByLabelText(/comment response text/i);
      expect(textarea).toHaveValue('');
    });
  });

  describe('Feature 2: Auto-categorize + Priority in CreateTicketPage', () => {
    it('classifies ticket and applies suggested category and priority to form', async () => {
      vi.mocked(ticketsApi.categorizeTicket).mockResolvedValue({
        category: 'Billing',
        priority: 'P1',
        confidence: 0.96,
        reasoning: 'Critical payment gateway disruption directly preventing revenue checkout.',
      });

      render(
        <QueryClientProvider client={queryClient}>
          <MemoryRouter initialEntries={['/tickets/new']}>
            <Routes>
              <Route path="/tickets/new" element={<CreateTicketPage />} />
            </Routes>
          </MemoryRouter>
        </QueryClientProvider>
      );

      const titleInput = screen.getByLabelText(/ticket subject/i);
      const descInput = screen.getByLabelText(/detailed description/i);

      fireEvent.change(titleInput, { target: { value: 'Payment 504 Outage' } });
      fireEvent.change(descInput, {
        target: { value: 'All transactions on Stripe are failing with 504 timeouts.' },
      });

      const classifyBtn = screen.getByRole('button', { name: /auto-classify with ai/i });
      fireEvent.click(classifyBtn);

      await waitFor(() => {
        expect(screen.getByText(/critical payment gateway disruption/i)).toBeInTheDocument();
      });

      expect(screen.getByText(/96% confidence/i)).toBeInTheDocument();

      // Click "Apply Suggestions"
      const applyBtn = screen.getByRole('button', { name: /apply suggestions/i });
      fireEvent.click(applyBtn);

      // Verify category input and priority select were updated
      const categoryInput = screen.getByLabelText(/category/i);
      const prioritySelect = screen.getByLabelText(/priority/i);

      expect(categoryInput).toHaveValue('Billing');
      expect(prioritySelect).toHaveValue('P1');
    });

    it('requires minimum title and description before calling AI triage', async () => {
      render(
        <QueryClientProvider client={queryClient}>
          <MemoryRouter initialEntries={['/tickets/new']}>
            <Routes>
              <Route path="/tickets/new" element={<CreateTicketPage />} />
            </Routes>
          </MemoryRouter>
        </QueryClientProvider>
      );

      const classifyBtn = screen.getByRole('button', { name: /auto-classify with ai/i });
      fireEvent.click(classifyBtn);

      await waitFor(() => {
        expect(
          screen.getByText(/please enter a ticket subject/i)
        ).toBeInTheDocument();
      });

      expect(ticketsApi.categorizeTicket).not.toHaveBeenCalled();
    });
  });
});
